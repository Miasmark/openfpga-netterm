#!/bin/bash
# Generate src/fpga/core/pll/pll_core.v with Quartus' ip-generate (altera_pll):
# 74.25 MHz in; outclk_0 = 49.5 MHz (clk_sys), outclk_1 = 12.375 MHz (clk_pix),
# outclk_2 = clk_pix at 90 degrees. Integer-N: N = 1, M = 12 (VCO
# 891 MHz), C0 = 18, C1 = C2 = 72.
#
# Runs inside raetro/quartus:21.1 (the build workflow calls it there):
#   docker run --rm -v "$PWD:/build" -w /build raetro/quartus:21.1 tools/gen_pll.sh
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
cd "$WORK"
ip-generate --remove-qsys-generate-warning --project-directory="$WORK" --output-directory="$WORK/pll_core" \
  --file-set=QUARTUS_SYNTH --component-name=altera_pll --output-name=pll_core \
  --system-info=DEVICE_FAMILY="Cyclone V" --system-info=DEVICE=5CEBA4F23C8 --system-info=DEVICE_SPEEDGRADE=8_H6 \
  --component-parameter=gui_device_speed_grade=8 --component-parameter=gui_pll_mode="Integer-N PLL" \
  --component-parameter=gui_reference_clock_frequency=74.25 --component-parameter=gui_operation_mode=direct \
  --component-parameter=gui_en_reconf=false --component-parameter=gui_number_of_clocks=3 \
  --component-parameter=gui_output_clock_frequency0=49.5 --component-parameter=gui_output_clock_frequency1=12.375 --component-parameter=gui_output_clock_frequency2=12.375 \
  --component-parameter=gui_ps_units2=degrees --component-parameter=gui_phase_shift_deg2=90.0 \
  --component-parameter=gui_en_adv_params=true \
  --component-parameter=gui_multiply_factor=12 --component-parameter=gui_divide_factor_n=1 \
  --component-parameter=gui_divide_factor_c0=18 --component-parameter=gui_divide_factor_c1=72 --component-parameter=gui_divide_factor_c2=72 \
  --component-parameter=gui_pll_auto_reset=Off
{
  echo "// The core PLL, generated by tools/gen_pll.sh (Quartus ip-generate,"
  echo "// altera_pll); everything below this comment is the tool's output."
  cat "$WORK/pll_core/pll_core.v"
} > "$ROOT/src/fpga/core/pll/pll_core.v"
grep -n "output_clock_frequency[012]\|phase_shift[012]\|pll_output_clk_frequency" "$ROOT/src/fpga/core/pll/pll_core.v"
rm -rf "$WORK"
